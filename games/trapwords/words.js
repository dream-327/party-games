/**
 * 获取指定类型的词库列表
 */
function getWordListByType(category = 'all', customWords = []) {
  let list = [];
  const customList = (Array.isArray(customWords) ? customWords : [])
    .map(w => String(w).trim())
    .filter(Boolean)
    .map(text => ({ text, type: '自定义' }));

  // 纯自定义模式：只使用玩家输入的词
  if (category === 'custom') {
    return customList.length > 0 ? customList : [{ text: '说“我没有填自定义词”', type: '自定义' }];
  }

  if (category === 'phrases') {
    list = phraseTraps.map(text => ({ text, type: '口头禅' }));
  } else if (category === 'actions') {
    list = actionTraps.map(text => ({ text, type: '小动作' }));
  } else if (category === 'interaction') {
    list = interactionTraps.map(text => ({ text, type: '互动套路' }));
  } else {
    // all 全部混合
    list = [
      ...phraseTraps.map(text => ({ text, type: '口头禅' })),
      ...actionTraps.map(text => ({ text, type: '小动作' })),
      ...interactionTraps.map(text => ({ text, type: '互动套路' }))
    ];
  }

  // 其他模式下，如果玩家输入了自定义词，也混合到总词库中
  if (customList.length > 0) {
    list = [...customList, ...list];
  }

  return list;
}

/**
 * 随机抽取一个禁忌词/动作
 */
function getRandomWord(category = 'all', customWords = [], usedTexts = new Set()) {
  const list = getWordListByType(category, customWords);
  const available = list.filter(item => !usedTexts.has(item.text));
  const pool = available.length > 0 ? available : list;
  const item = pool[Math.floor(Math.random() * pool.length)];
  return { ...item };
}

/**
 * 随机抽取一个聚会惩罚
 */
function getRandomPunishment(excludePunishment = null) {
  const pool = punishments.filter(p => p !== excludePunishment);
  const candidates = pool.length > 0 ? pool : punishments;
  return candidates[Math.floor(Math.random() * candidates.length)];
}

